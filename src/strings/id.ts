/** "Kamu menyelesaikan “Laporan Lab”." Built here so the database keeps only names. */
export function trailSentence(item: ActivityItem): string {
  const who = id.trail.actor[item.actor];
  const name = `“${item.summary}”`;
  const thing: Partial<Record<ActivityItem["entity"], string>> = {
    task: "tugas",
    project: "proyek",
    milestone: "tonggak",
    event: "jadwal",
    reminder: "pengingat",
    routine: "rutinitas",
    area: "ruang",
    file: "file",
    journal: "catatan",
    learning_item: "materi",
    track: "jalur",
    collection: "koleksi",
    ctf_event: "kompetisi",
    studio_project: "proyek Studio",
    studio_ledger: "catatan Studio",
    studio_prd: "PRD",
    studio_roadmap: "roadmap",
    studio_checkpoint: "checkpoint",
    studio_task: "tugas checkpoint",
    studio_report: "laporan",
    studio_request: "permintaan",
  };
  const noun = thing[item.entity] ?? "";
  const tidy = (text: string) => text.replace(/\s{2,}/g, " ");
  // Sentences that read better than the general ones.
  if (item.entity === "learning_session") {
    return item.verb === "deleted" ? `${who} menghapus satu sesi ${name}.` : `${who} belajar ${name}.`;
  }
  if (item.entity === "file" && item.actor === "hub") {
    if (item.verb === "moved") return `Hub menemukan ${name} di tempat barunya.`;
    if (item.verb === "updated") return `Hub tidak menemukan ${name} di tempatnya.`;
  }
  if (item.entity === "file" && item.verb === "moved") return `${who} menunjukkan letak baru ${name}.`;
  if (item.entity === "settings" && item.summary === "gemini_key") {
    return item.verb === "deleted" ? `${who} menghapus API key Gemini.` : `${who} menyimpan API key Gemini.`;
  }
  if (item.verb === "detached") return `${who} melepas lampiran ${name}.`;
  switch (item.verb) {
    case "completed":
      return `${who} menyelesaikan ${name}.`;
    case "reopened":
      return `${who} membuka lagi ${name}.`;
    case "created":
      return tidy(`${who} menambahkan ${noun} ${name}.`);
    case "focused":
      return `${who} memilih fokus.`;
    case "approved":
      return tidy(`${who} menyetujui ${noun} ${name}.`);
    case "closed":
      return `${who} menutup hari.`;
    case "deleted":
      return tidy(`${who} menghapus ${noun} ${name}.`);
    case "restored":
      return tidy(`${who} mengembalikan ${noun} ${name}.`);
    case "attached":
      return `${who} melampirkan ${name}.`;
    case "moved":
      return tidy(`${who} memindahkan ${noun} ${name}.`);
    case "reminded":
      return `${who} mengingatkan ${name}.`;
    case "snoozed":
      return `${who} menunda ${name}.`;
    case "cancelled":
      return tidy(`${who} membatalkan ${noun} ${name}.`);
    default:
      return tidy(`${who} mengubah ${noun} ${name}.`);
  }
}
